const SPACE = GLYPHS[' '] as string;

function normalise(ch: string): string {
  return ch.toUpperCase();
}

/** True when the font has a bitmap for `ch` (case-insensitive). */
export function hasGlyph(ch: string): boolean {
  return normalise(ch) in GLYPHS;
}

/** The raw 35-character bit string for `ch`; unknown characters render as space. */
export function glyphBits(ch: string): string {
  return GLYPHS[normalise(ch)] ?? SPACE;
}

/** The glyph as 7 rows of 5 bits. */
export function glyphRows(ch: string): (0 | 1)[][] {
  const bits = glyphBits(ch);
  const rows: (0 | 1)[][] = [];
  for (let y = 0; y < GLYPH_H; y++) {
    const row: (0 | 1)[] = [];
    for (let x = 0; x < GLYPH_W; x++) row.push(bits.charCodeAt(y * GLYPH_W + x) === 49 ? 1 : 0);
    rows.push(row);
  }
  return rows;
}

/** Width in dots of `text` drawn at `scale` (no trailing gap). */
export function textWidth(text: string, scale = 1): number {
  const n = [...text].length;
  return n === 0 ? 0 : (n * GLYPH_ADVANCE - 1) * scale;
}
